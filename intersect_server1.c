static int couteauSR(int n_fixed, int max_depth, uint8_t (**XS)[tobytes(n_fixed)], uint8_t (*R)[tobytes(n_fixed)], uint32_t (*A)[n_fixed], int *intersect_indices, bool *t, int *js, int *js_acc){
    
    int l = js[0];
    int nbytes_fixed = tobytes(n_fixed);
    int noOTs_j = js_acc[max_depth];
    uint8_t (*xs)[nbytes_fixed] = malloc(nbytes_fixed * (noOTs_j + rsize));
    memset(xs, 0, nbytes_fixed * (noOTs_j + rsize));
    
    if(!xs){
        printf("could not allocate xs\n");
        return -1;
    }
    
    int indexlen = l / L;
    int acc;

    //server1 sets x1 = x for every record
    for(int i = 0; i < nbytes_fixed; i++)
        for(int j = 0; j < indexlen; j++)
            for(int k = 0; k < L; k++)
                xs[j * L + k][i] = D1(intersect_indices[j] * L + k, i) ^ (255 * t[j * L + k]);

    if(l == 1 || max_depth == 0){
        *XS = realloc(xs, rsize * nbytes_fixed);
        printf("skipping size reduction\n");
        return 0;
    }
    for(int depth = 0; depth < max_depth; depth++){
        int arr_size = nbytes_fixed * js[depth];
        uint8_t (*z1)[nbytes_fixed] = malloc(arr_size), (*z2)[nbytes_fixed] = NULL, (*z)[nbytes_fixed] = z2; //reuse z2 array
        if(!z1){
            printf("could not allocate z1\n");
            return -1;
        }
        //server1 sends for each record: z1 = r[i] ^ x[i];
        for(int i = 0; i < nbytes_fixed; i++)
            for(int j = 0; j < js[depth]; j++)
                z1[j][i] = R[js_acc[depth] + j][i] ^ xs[js_acc[depth] + j][i];
        
        //servers exchange z1 and z2
        uint8_t *recv_arr;
        uint64_t count;
        if(send_8(s2_fd, (uint8_t *)z1, arr_size) != 0){
            fprintf(stderr, "send z1 to s2 failed\n");
            return -1;
        }
        if(receive_8(s2_fd, &recv_arr, &count) == 0 && count == arr_size)
            z2 = (void *)recv_arr;
        else{
            fprintf(stderr, "receive z2 from s2 failed\n");
            return -1;
        }

        //and calculate z as z = z1 ^ z2
        for(int i = 0; i < nbytes_fixed; i++)
            for(int j = 0; j < js[depth]; j++)
                z[j][i] = z1[j][i] ^ z2[j][i];
        
        //server1 calculates what will become xs[i+1]
        int byte = 0, bit = 0;
        for(int i = 0; i < n_fixed; i++){
            if(bit > 7){
                bit = 0;
                byte++;
            }
            acc = 0;
            for(int j = 0; j < js[depth]; j++){
                acc += (int)pow(-1, (z[j][byte] >> bit & 1)) * A[js_acc[depth] + j][i];
            }
            acc = FF_convert(-acc, js[depth] + 1);
            for(int j = 0; j < js[depth + 1]; j++)
                xs[js_acc[depth + 1] + j][byte] += (acc >> j & 1) << bit;
            bit++;
        }
        free(z1);
        free(z2);
    }
    *XS = &xs[js_acc[max_depth]];
    XS = realloc(xs, rsize * nbytes_fixed);
    if(verbose) printf("finished couteauSR()\n");
    return 0;
}

static int couteauPS(int n_fixed, int max_depth, uint8_t **Z1, uint8_t (*XS)[tobytes(n_fixed)], uint8_t (*r)[tobytes(n_fixed)], uint8_t (*a)[tobytes(n_fixed)]){


    int nbytes_fixed = tobytes(n_fixed);
    bool I[expon][rsize];
    powset(rsize, I, expon);
    //server1

    *Z1 = malloc(nbytes_fixed * sizeof(uint8_t));
    if(!Z1){
        printf("could not allocate Z1\n");
        return -1;
    }

    uint8_t *alpha = malloc(nbytes_fixed), *beta = NULL,
    (*Alpha)[nbytes_fixed] = malloc(nbytes_fixed * expon * sizeof(uint8_t)), (*Beta)[nbytes_fixed] = NULL,
    (*EX)[nbytes_fixed] = malloc(nbytes_fixed * expon * sizeof(uint8_t));
    if(!alpha || !Alpha || !EX){
        printf("could not allocate alpha, Alpha or EX\n");
        return -1;
    }

    uint8_t acc1;
    for(int i = 0; i < nbytes_fixed; i++){
        for(int k = 0; k < expon; k++){
            acc1 = 255;
            for(int j = 0; j < rsize; j++){
                if(I[k][j])
                    acc1 &= 255 ^ XS[j][i];
            }
            EX[k][i] = acc1;
            Alpha[k][i] = r[k][i] ^ acc1;
        }
    }
    randombytes_buf(alpha, nbytes_fixed);

    //servers send each other alpha and beta (+Alpha and Beta)
    uint8_t *recv_arr;
    uint64_t count;
    if(send_8(s2_fd, (uint8_t *)alpha, nbytes_fixed) != 0){
        fprintf(stderr, "send alpha to s2 failed\n");
        return -1;
    }
    if(receive_8(s2_fd, &recv_arr, &count) == 0 && count == nbytes_fixed)
        beta = (void *)recv_arr;
    else{
        fprintf(stderr, "receive beta from s2 failed\n");
        return -1;
    }

    if(send_8(s2_fd, (uint8_t *)Alpha, nbytes_fixed * expon) != 0){
        fprintf(stderr, "send Alpha to s2 failed\n");
        return -1;
    }
    if(receive_8(s2_fd, &recv_arr, &count) == 0 && count == nbytes_fixed * expon)
        Beta = (void *)recv_arr;
    else{
        fprintf(stderr, "receive Beta from s2 failed\n");
        return -1;
    }

    //server1
    uint8_t acc2;
    for(int i = 0; i < nbytes_fixed; i++){
        acc1 = 0;
        acc2 = 255;
        for(int k = 0; k < expon; k++)
            acc1 ^= a[k][i] ^ (Beta[k][i] & EX[k][i]);
        for(int j = 0; j < rsize; j++)
            acc2 &= 255 ^ XS[j][i];
        *Z1[i] = acc1 ^ acc2 ^ alpha[i] ^ beta[i];
    }

    free(XS);
    free(alpha);
    free(beta);
    free(Alpha);
    free(Beta);
    if(verbose) printf("finished couteauPS()\n");
    return 0;
}

