/*
 * Main method for computing intersection count. Performs distributed AND on all records.
 * Input: Server 1's dataset (global variable D), or alternatively alt_D, used for
 * CouteauHybrid only (alt_D is the output of the size reduction protocol from Couteau)
 * Output:
*D_i is each server's boolean share of the record data, I_i is the computed intersection shares
*/
static int intersectminus(int n_fixed, int l, int L, int no_multis_bytes, uint8_t (*alt_D)[tobytes(n_fixed)], uint8_t (*T1)[no_multis_bytes], uint8_t **Z1, int *intersect_indices, bool *t){
    int nbytes_fixed = tobytes(n_fixed);
    int lhalf = l - (l / 2);
    int initsize = lhalf * nbytes_fixed * sizeof(uint8_t);
    int de_size = (l / 2) * nbytes_fixed * sizeof(uint8_t);
    uint8_t (*I1)[nbytes_fixed] = malloc(initsize);
    if(!I1){
        fprintf(stderr, "could not allocate I1\n");
        return -1;
    }

    uint8_t (*d1)[nbytes_fixed] = malloc(de_size), (*e1)[nbytes_fixed] = malloc(de_size);
    uint8_t (*d2)[nbytes_fixed] = NULL, (*e2)[nbytes_fixed] = NULL; // should get malloc'ed by recv()
    uint8_t (*d)[nbytes_fixed] = NULL, (*e)[nbytes_fixed] = NULL; // will reuse from d2 and e2
    if(!d1 || !e1){
        fprintf(stderr, "could not allocate d or e arrays\n");
        return -1;
    }

    int index1, index2;
    int index_len = l / L;
    int no_pairs = l / 2; //e.g. if we have 7 indices, we have 3 pairs and 1 leftover
    bool uneven = no_pairs * 2 != l;
    l -= no_pairs;

    int index = 0, subindex = 0, j = 0;
    for(int pair = 0; pair < no_pairs; pair++){
        for(int i = 0; i < nbytes_fixed; i++){
            index1 = intersect_indices[index] * L + subindex;
            index2 = subindex + 1 == L? intersect_indices[index + 1] * L: index1 + 1;
            if(alt_D){
                //printf("using altD\n");
                //server 1 computes intermediate values d1 = x1 - a1
                d1[pair][i] = alt_D[index1][i] ^ (255 * t[index * L + subindex]) ^ T1[0][j];
                //e1 = y1 - b1
                e1[pair][i] = alt_D[index2][i] ^ (255 * t[index * L + subindex + 1]) ^ T1[1][j++];
            }
            else{
                d1[pair][i] = D1(index1, i) ^ (255 * t[index * L + subindex]) ^ T1[0][j];
                e1[pair][i] = D1(index2, i) ^ (255 * t[index * L + subindex + 1]) ^ T1[1][j++];
            }
        }
        subindex++;
        if(subindex == L){
            subindex -= L;
            index++;
        }
        subindex++;
        if(subindex == L){
            subindex -= L;
            index++;
        }
    }

    uint8_t *recv_arr;
    uint64_t count;
    if(send_8(s2_fd, (uint8_t *)d1, de_size) != 0){
        fprintf(stderr, "send d1 to s2 failed\n");
        return -1;
    }
    if(receive_8(s2_fd, &recv_arr, &count) == 0 && count == de_size){
        d2 = (void *)recv_arr;
        d = d2;
    }
    else{
        fprintf(stderr, "receive d2 from s2 failed\n");
        return -1;
    }

    if(send_8(s2_fd, (uint8_t *)e1, de_size) != 0){
        fprintf(stderr, "send e1 to s2 failed\n");
        return -1;
    }

    if(receive_8(s2_fd, &recv_arr, &count) == 0 && count == de_size){
        e2 = (void *)recv_arr;
        e = e2;
    }
    else{
        fprintf(stderr, "receive e2 from s2 failed\n");
        return -1;
    }
    j = 0;
    for(int pair = 0; pair < no_pairs; pair++){
        for(int i = 0; i < nbytes_fixed; i++){
            //now we assume both servers have all parts to reconstruct d and e, and thus both calculate:
            // --------------------
            d[pair][i] = d1[pair][i] ^ d2[pair][i];
            e[pair][i] = e1[pair][i] ^ e2[pair][i];
            //server 1 computes z1 as d*b1 + e*a1 + c1
            I1[pair][i] = (d[pair][i] & T1[1][j]) ^ (e[pair][i] & T1[0][j]) ^ T1[2][j];
            j++;
        }
    }

    free(d2);
    free(e2);

    if(uneven){
        int leftoverindex = (intersect_indices[index_len - 1] + 1) * L - 1;
        for(int i = 0; i < nbytes_fixed; i++){
            if(alt_D){
                //printf("using altD\n");
                I1[no_pairs][i] = alt_D[leftoverindex][i] ^ (255 * t[index * L + subindex]); }
            else I1[no_pairs][i] = D1(leftoverindex, i) ^ (255 * t[index * L + subindex]);
        }
    }

    int jcheckpoint, spacing;
    int no_rounds = (int)ceil(log2(l));
    for(int round = 0; round < no_rounds; round++){
        no_pairs = l / 2; //e.g. if we have 7 indices, we have 3 pairs and 1 leftover
        l -= no_pairs;
        spacing = (int)pow(2, round);
        jcheckpoint = j;
        for(int pair = 0; pair < no_pairs; pair++){
            index1 = 2*pair*spacing; //first index of the pair
            index2 = spacing*(2*pair + 1); //second index of the pair=
            for(int i = 0; i < nbytes_fixed; i++){
                d1[pair][i] = I1[index1][i] ^ T1[0][j];
                e1[pair][i] = I1[index2][i] ^ T1[1][j++];
            }
        }
        j = jcheckpoint;
        int sendsize = no_pairs * nbytes_fixed;
        if(send_8(s2_fd, (uint8_t *)d1, sendsize) != 0){
            fprintf(stderr, "send d1 to s2 failed\n");
            return -1;
        }
        if(receive_8(s2_fd, &recv_arr, &count) == 0 && count == sendsize){
            d2 = (void *)recv_arr;
            d = d2;
        }
        else{
            fprintf(stderr, "receive d2 from s2 failed\n");
            return -1;
        }

        if(send_8(s2_fd, (uint8_t *)e1, sendsize) != 0){
            fprintf(stderr, "send e1 to s2 failed\n");
            return -1;
        }

        if(receive_8(s2_fd, &recv_arr, &count) == 0 && count == sendsize){
            e2 = (void *)recv_arr;
            e = e2;
        }
        else{
            fprintf(stderr, "receive d2 from s2 failed\n");
            return -1;
        }

        //servers publish shares, i.e. server 1 sends D1 and E1, server 2 similarly
        for(int pair = 0; pair < no_pairs; pair++){
            index1 = 2*pair*spacing;
            for(int i = 0; i < nbytes_fixed; i++){
                //now both servers have all parts to reconstruct D and E, and thus both calculate:
                d[pair][i] = d1[pair][i] ^ d2[pair][i];
                e[pair][i] = e1[pair][i] ^ e2[pair][i];
                //server 1 computes z1 as d*b1 + e*a1 + c1
                I1[index1][i] = (d[pair][i] & T1[1][j]) ^ (e[pair][i] & T1[0][j]) ^ T1[2][j];
                j++;
            }
        }
        free(d2);
        free(e2);
    }

    *Z1 = realloc(I1, nbytes_fixed);
    if(!Z1){
        fprintf(stderr, "error reallocating Z1\n");
        return -1;
    }
    free(d1);
    free(e1);
    return 0;
}

