static int s2_connect(){
    struct sockaddr_in address;
    int opt = 1;
    int sendbuf = 4 * 1024 * 1024;
    int recvbuf = 4 * 1024 * 1024;
    socklen_t addrlen = sizeof(address);

    // Creating socket file descriptor
    if((self_fd = socket(AF_INET, SOCK_STREAM, 0)) < 0) {
        perror("socket failed");
        return -1;
    }

    // Forcefully attaching socket to the port 8080
    if(setsockopt(self_fd, SOL_SOCKET, SO_REUSEADDR, &opt, sizeof(opt))){
        perror("setsockopt");
        return -1;
    }
    if(setsockopt(self_fd, SOL_SOCKET, SO_REUSEPORT, &opt, sizeof(opt))){
        perror("setsockopt");
        return -1;
    }
    if(setsockopt(self_fd, SOL_SOCKET, SO_SNDBUF, &sendbuf, sizeof(sendbuf))){
        perror("setsockopt");
        return -1;
    }
    if(setsockopt(self_fd, SOL_SOCKET, SO_RCVBUF, &recvbuf, sizeof(recvbuf))){
        perror("setsockopt");
        return -1;
    }

    address.sin_family = AF_INET;
    address.sin_addr.s_addr = INADDR_ANY;
    address.sin_port = htons(SPORT);

    if(bind(self_fd, (struct sockaddr*)&address, sizeof(address)) < 0){
        perror("bind failed");
        return -1;
    }
    if(listen(self_fd, 3) < 0){
        perror("listen");
        return -1;
    }
    fprintf(stderr, "waiting for connection to s2...\n");
    if ((s2_fd = accept(self_fd, (struct sockaddr*)&address, &addrlen)) < 0){
        perror("accept");
        return -1;
    }
    fprintf(stderr, "Connected to s2\n");
    return s2_fd;
}

